<?php

namespace App\Observers;

use App\Models\SystemSetting;
use Illuminate\Support\Facades\File;
use Illuminate\Support\Facades\Log;

class SystemSettingObserver
{
    /**
     * Handle the SystemSetting "saved" event.
     * We use saved so it catches both created and updated.
     */
    public function saved(SystemSetting $setting)
    {
        \Illuminate\Support\Facades\Cache::forget('system_settings_v2');
        
        // Check if any SIP related fields were modified
        if ($setting->wasChanged(['asterisk_sip_host', 'asterisk_sip_username', 'asterisk_sip_password', 'asterisk_port'])) {
            $this->generateAsteriskTrunk($setting);
        }
    }

    private function generateAsteriskTrunk(SystemSetting $setting)
    {
        if (empty($setting->asterisk_sip_host) || empty($setting->asterisk_sip_username)) {
            Log::info('Skipping Asterisk Trunk generation: missing host or username.');
            return;
        }

        $password = '';
        if (!empty($setting->asterisk_sip_password)) {
            try {
                $password = decrypt($setting->asterisk_sip_password);
            } catch (\Exception $e) {
                Log::error('Failed to decrypt asterisk sip password: ' . $e->getMessage());
            }
        }

        $trunkName = 'uztelecom_trunk'; // Can be dynamic if needed
        $host = $setting->asterisk_sip_host;
        $username = $setting->asterisk_sip_username;
        $port = $setting->asterisk_port ?? 5060;

        $conf = <<<EOT
; Auto-generated by Sher-Dor ERP System Setting Observer
; Do not edit manually

[$trunkName]
type=registration
outbound_auth=$trunkName
server_uri=sip:$host:$port
client_uri=sip:$username@$host:$port
retry_interval=60

[$trunkName]
type=auth
auth_type=userpass
password=$password
username=$username

[$trunkName]
type=aor
contact=sip:$host:$port

[$trunkName]
type=endpoint
context=from-trunk
disallow=all
allow=alaw,ulaw
outbound_auth=$trunkName
aors=$trunkName
from_user=$username
from_domain=$host

[$trunkName]
type=identify
endpoint=$trunkName
match=$host

EOT;

        // Note: For this to work in production, Laravel needs write access to this path
        $path = '/etc/asterisk/pjsip_custom_trunk.conf';
        
        // For local dev, write to a temp directory if /etc/asterisk is not accessible
        if (!is_writable('/etc/asterisk')) {
            $path = storage_path('app/pjsip_custom_trunk.conf');
            Log::warning("/etc/asterisk is not writable. Writing config to {$path} instead.");
        }

        try {
            File::put($path, $conf);
            Log::info("Asterisk PJSIP Trunk config updated at {$path}");

            // Reload Asterisk PJSIP
            // In production, sudoers must be configured to allow this command without password
            $output = shell_exec('sudo asterisk -rx "pjsip reload" 2>&1');
            Log::info("Asterisk Reload Output: " . $output);

        } catch (\Exception $e) {
            Log::error('Failed to write Asterisk PJSIP config: ' . $e->getMessage());
        }
    }
}
