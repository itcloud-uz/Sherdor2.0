    <p>5.2. Шартнома Қонун ҳужжатларида белгиланган тартибда хамда томонлар келишувига асосан ўзгартирилиши ёки бекор қилиниши мумкин. Шартномани бир томонлама бекор килинишига ушбу шартноманинг 2.2., 2.4. бандларига асосан ва унга узгартириш ва кушимчалар киритилишига амалдаги конунлар ва узаро келишувга асосан иккинчи томонни 10 (ун) кун муддат олдин ёзма равиш огохлантириш оркали йул куйилади.</p>
    <p>5.3. Томонларнинг жавобгарлиги Узбекистон Республикасининг 29.08.1998 йилдаги “Хужалик юритувчи субъектларнинг шартномавий-хукукий базаси тугрисида”ги конун, амалдаги бошка конунлар ва меъёрий хужжатларга асосан белгиланади.</p>

