    <div class="section-header">6. МАХСУС ШАРТЛАР</div>
    <p>6.1 «Харидор» томонидан 3.2-банд бўйича тўловни амалга ошириш муддатлари бажарилмаган тақдирда ушбу шартнома бўйича, белгиланган муддатлар тугагандан сўнг «Корхона» «Объект» ни учинчи томонга янги шартнома тузиш йўли билан беришга ҳақли, «Харидор» билан шартномани автоматик равишда бекор қилади. Агар «Харидор» 3.2-бандда кўрсатилган бошланғич 30 (ўттиз) % миқдорни тўласаю, 3.2-банддаги қолган қисмини кўрсатилган миқдорда тўлиқ тўламаса «Корхона» «Объект» ни учинчи шахсга «Харидор» билан оғзаки (телефон орқали, хабарнома ёки СМС юбориш орқали) ёки ёзма равишда бекор қилиш орқали янги шартнома тузиш ҳуқуқига эга. «Харидор» га оғзаки (телефон орқали, хабарнома ёки СМС юбориш орқали) ёки ёзма равишда хабарнома берилган кундан бошлаб 10 (ўн) кундан кейин мазкур шартнома бекор қилинади.</p>
    <p>6.2 «Харидор» га ушбу шартномада кўрсатилган 5.3-банднинг учинчи қисмига мувофиқ «Харидор» тўлаган тўловлар қайтарилади.</p>
    <p>6.3 Томонлар ушбу шартнома бўйича ҳар қандай маълумотларга таълуқли бўлган масалаларда маҳфийликни сақлаш мажбурияти оладилар, уларнинг ошкор қилиниши томонларнинг мулкий ёки бошқа зарар етказилиши мумкин. Акс ҳолда айбдор томон бошқа томонга етказилган зарарни қоплаш мажбуриятини олади.</p>
    <p>6.4 Агар ушбу шартноманинг 5.2-бандида белгиланган муддат ичида квартирада нуқсон ва камчиликлар бўлмасаю, топшириш ва қубул-қилиш далолатномаси орқали олишдан бош тортса «Корхона» Ўзбекистон Республикасининг амалдаги қонунчилигида белгиланган тартибда қўшимча далолатнома орқали квартирани «Харидор» га бериш тўғрисида бир томонлама далолатнома тузишга ҳақли. Шу билан бирга вақт, техник хизмат кўрсатиш (коммунал хизматлар ва бошқа ҳаражатларни ўз ичига олган ҳолда) ва квартирага шикаст етказиш ва бошқа зарарларни бир томонлама далолатнома тузилган кундан бошлаб «Харидор» га ўтказилган деб ҳисобланади.</p>

    <div class="section-header">7. ФОРС-МАЖОР ҲОЛАТЛАРИ</div>
    <p>7.1 Томонларга боғлиқ бўлмаган фавқулодда ҳолатлар (сув тошқини, ёнғин, ер қимирлаши ва бошқа офатлар, ҳукумат қарорлари, ҳарбий ҳолатлар ва бошқа томонлар назорат қила олмайдиган ҳолатлар) оқибатида мазкур шартномада кўрсатилган мажбуриятлар қисман ёки тўлиқ бажарилмаса, томонлар Ушбу мажбуриятлар бажарилмаганлиги учун жавобгарликдан озод қилинадилар.</p>
    <p>7.2 Форс-мажор ҳолатлари юз берганида томонлар бир-бирларини бу ҳолатлар тўғрисида 1 (бир) ой ичида хабардор қилади ва шартнома бўйича мажбуриятларнинг амалга оширишининг кечиктирилиши борасида ёхуд шартномага қўшимчалар киритиш борасида музокара олиб борадилар.</p>
    <p>7.3 Агарда форс-мажор ҳолатлари 6 (олти) ойдан кўп давом этса, томонлар шартнома бўйича мажбуриятларнинг амалга оширишнинг алтернатив усулини танлашлари ёхуд шартномани бекор қилишлари мумкин.</p>
    <p>7.4 Форс-мажор ҳолатлари ваколатли давлат органлар томонидан тасдиқланиши лозим.</p>
    <p>7.5 Форс-мажор ҳолатлари кучга кирган вақт шартнома бўйича мажбуриятларни бажариш муддатига кирмайди.</p>

    <div class="section-header">8. НИЗОЛАРНИ ХАЛ КИЛИШ ТАРТИБИ.</div>
    <p>8.1 Ушбу шартнома буйича ёки у билан боғлик холда томонлар ўртасида келиб чиқадиган барча низо ва зиддиятлар ёзма талабнома билдириш тартибига риоя қилинган холда ҳал этилади.</p>
    <p>8.2 Билдирган талабномасига конунда белгиланган 1 (бир) ойлик муддат ичида жавоб олмаган ёки талаблари қаноатлантирилмаган такдирда, хукуки бузилган деб ҳисобловчи томон, Ушбу шартнома юзасидан ёки у билан боғлиқ ҳолда томонлар ўртасида келиб чиқадиган низо ва зиддиятлар фуқаролик ишлари бўйича судлар томонидан кўриб чиқилади.</p>

    <div class="section-header">9. ШАРТНОМАГА ЎЗГАРТИРИШ ВА ҚЎШИМЧАЛАР КИРИТИШ ТАРТИБИ ҲАМДА УНИ БЕКОР ҚИЛИШ АСОСЛАРИ</div>
    <p>9.1 Шартномага ҳар қандай ўзгартириш ва қўшимчалар ёзма равишда бажарилган ва томонларнинг ваколатли шахслари томонидан имзоланган ҳолдагина ҳақиқийдир ва томонлар тасдиқланган кундан бошлаб кучга киради.</p>
    <p>9.2 Шартнома томонларнинг ўзаро келишувига мувофиқ ёки бир томон томонидан шартнома шартлари жиддий бузилган тақдирда иккинчи томоннинг талабига биноан бекор қилиниши мумкин.</p>
    <p>9.3 Шартномани бир томонлама бекор қилиш ёзма тарзда огоҳлантирилган тартибда амалга оширилади.</p>
    <p>9.4 «Ҳиссадор» томонидан шартнома шартлари бузилган тақдирда «Қурувчи» «Ҳиссадор»ни ёзма огохлантириб, шартномани бекор қилиш ҳуқуқига эга.</p>
    <p>9.5 Шартномани муддатидан олдин бекор қилишга Ўзбекистон Республикасини амалдаги қонун хужжатларида назарда тутилган асосларга кўра, етказилган зарар қопланган ҳолда йул қуйилади.</p>

    <div class="section-header">10. БОШҚА ШАРТЛАР.</div>
    <p>10.1 Шартнома томонлар имзоланган пайтдан бошлаб кучга киради ва шартномавий мажбуриятлар лозим даражада бажарилгунга қадар амалда бўлади.</p>
    <p>10.2 Томонлар ушбу шартномани имзолаётган вақтда улар алдаш, зўравонлик, ёмон келишув ва мураккаб вазиятлар таъсирида эмаслигини тасдиқлайдилар. Улар шартнома матнини ўқишди ва бу шартномада қандай шартлар тўзилганлигини, шунингдек, шартнома матни томонларнинг ҳохиш-иродасининг ҳақиқий ифодасига тўғри келишини аниқ тушинишди.</p>
    <p>10.3 Шартнома икки нусхада тузилган бўлиб, ҳар иккаласи хам бир хил юридик кучга эга ва томонларга бир нусхадан берилади.</p>
    <p>10.4 Шартномага иловалар унинг ажралмас қисмини бўлиб ҳисобланади.</p>
    <p>10.5 Томонлар ўзларининг юридик манзиллари ва бошқа реквизитларини ўзгартирган тақдирда бир-бирларини 3 (уч) кунлик муддатда ушбу ҳолат тўғрисида хабардор қилишни шарт.</p>
    <p>10.6 Томонларга нисбатан фақатгина мазкур шартномада белгиланган жавобгарлик чоралари кулланилиши мумкин.</p>

